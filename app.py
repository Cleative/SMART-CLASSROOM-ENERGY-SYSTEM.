from pathlib import Path
import json
import streamlit as st
import pandas as pd
from joblib import load
from src.lighting_policy import FEATURES, lighting_policy, validate_inputs

ROOT = Path(__file__).resolve().parent
MODEL_PATH = ROOT / "models" / "decision_tree.joblib"
META_PATH = ROOT / "models" / "model_metadata.json"

st.set_page_config(page_title="Smart Classroom Energy System", page_icon="💡", layout="wide")
st.title("💡 Smart Classroom Energy System")
st.caption("Decision-support demonstration • Synthetic data • No physical hardware control")
st.warning("This project uses synthetic, policy-labelled data. Predictions are recommendations only; they do not switch real lights or prove energy savings.")

@st.cache_resource
def load_artifacts():
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(f"Model not found: {MODEL_PATH}. Run `python -m src.generate_dataset` and `python -m src.train_model` from the project directory.")
    if not META_PATH.is_file():
        raise FileNotFoundError(f"Model metadata not found: {META_PATH}. Retrain the model.")
    model = load(MODEL_PATH)
    metadata = json.loads(META_PATH.read_text(encoding="utf-8"))
    if metadata.get("features") != FEATURES:
        raise ValueError("Model metadata feature order does not match application features.")
    if list(model.feature_names_in_) != FEATURES:
        raise ValueError("Saved model feature order does not match application features.")
    if set(model.classes_) != {"OFF", "ON"}:
        raise ValueError("Saved model does not contain the expected OFF and ON classes.")
    return model, metadata

try:
    model, metadata = load_artifacts()
except Exception as exc:
    st.error(f"Could not load model artifacts: {exc}")
    st.stop()

left, right = st.columns([1, 1])
with left:
    st.subheader("Classroom input panel")
    lux = st.number_input("Ambient light level (lux)", min_value=0.0, max_value=5000.0, value=180.0, step=10.0,
                          help="Manual input for this demonstration; not a live sensor reading.")
    motion = st.selectbox("Motion detected?", options=[1,0], format_func=lambda x: "Yes" if x else "No")
    hour = st.slider("Hour of day", min_value=0, max_value=23, value=10, help="Use 24-hour time.")
    scheduled = st.selectbox("Scheduled classroom day?", options=[1,0], format_func=lambda x: "Yes" if x else "No")
    run = st.button("Recommend lighting action", type="primary", use_container_width=True)

with right:
    st.subheader("Model information")
    st.write(f"**Model:** {metadata['model_name']}")
    st.write(f"**Dataset:** {metadata['dataset_source']} — synthetic demonstration data")
    st.write(f"**Training records:** {metadata['training_records']:,}")
    st.write(f"**Held-out test records:** {metadata['test_records']:,}")
    metrics_path = ROOT/"results"/"metrics.json"
    if metrics_path.exists():
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        st.metric("Held-out test accuracy", f"{metrics['accuracy']:.1%}")
        st.caption("Accuracy is against synthetic labels generated by the policy, not a real-world performance guarantee.")
    cm_path = ROOT/"results"/"confusion_matrix.csv"
    if cm_path.exists():
        st.write("Confusion matrix (actual rows × predicted columns; class order OFF, ON)")
        st.dataframe(pd.read_csv(cm_path, index_col=0), use_container_width=True)

if run:
    try:
        vals = validate_inputs(lux, int(motion), int(hour), int(scheduled))
        X = pd.DataFrame([[vals[f] for f in FEATURES]], columns=FEATURES)
        prediction = str(model.predict(X)[0])
        baseline = lighting_policy(lux, int(motion), int(hour), int(scheduled))
        st.divider()
        st.subheader("Prediction")
        c1,c2 = st.columns(2)
        c1.metric("Decision Tree recommendation", prediction)
        c2.metric("Transparent policy baseline", baseline)
        st.write("**Inputs used**")
        st.dataframe(pd.DataFrame([vals]), use_container_width=True)
        if prediction == "ON":
            st.success("The trained Decision Tree recommends ON for these inputs.")
        else:
            st.info("The trained Decision Tree recommends OFF for these inputs.")
        if prediction != baseline:
            st.warning("The model and policy disagree. Investigate this discrepancy; the model may only approximate the policy.")
        else:
            st.write("The model agrees with the transparent policy for this input.")
        if hasattr(model, "predict_proba"):
            probs = dict(zip(model.classes_, model.predict_proba(X)[0]))
            st.write("**Model class estimates** (not probabilities of guaranteed real-world correctness)")
            st.write(" • ".join(f"{k}: {v:.1%}" for k,v in probs.items()))
        st.caption("Recommendation only. No relay, lamp, ESP32, Arduino, or building system is controlled.")
    except ValueError as exc:
        st.error(f"Invalid input: {exc}")

st.divider()
st.subheader("About this demonstration")
st.write("The model learns from a generated dataset whose target is defined by an explicit policy: scheduled day, motion, hour from 07:00 up to but not including 18:00, and light below 400 lux. The project needs independently reviewed real classroom observations before any real-world claims or deployment.")
